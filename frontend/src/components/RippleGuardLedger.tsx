import React, { useState } from 'react';
import { ShieldCheck, CheckCircle, XCircle, Info, UserCheck, Clock, Bus, ArrowRight, ShieldAlert } from 'lucide-react';
import type { TransferCard } from '../types';

interface RippleGuardLedgerProps {
  transfers: TransferCard[];
  scenarioName: string;
  onApprove: (transferId: string, operatorId: string) => void;
  onReject: (transferId: string, operatorId: string) => void;
}

export const RippleGuardLedger: React.FC<RippleGuardLedgerProps> = ({
  transfers,
  scenarioName,
  onApprove,
  onReject,
}) => {
  const [operatorId, setOperatorId] = useState('OP-402');

  return (
    <div className="bg-slate-900/90 border border-slate-800 rounded-2xl p-5 shadow-2xl backdrop-blur mb-6">

      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-4 border-b border-slate-800">
        <div>
          <div className="flex items-center space-x-2">
            <ShieldCheck className="w-5 h-5 text-indigo-400" />
            <h2 className="text-lg font-bold text-white tracking-tight">RippleGuard Explainable Transfer Ledger</h2>
            <span className="text-[10px] bg-indigo-500/20 text-indigo-300 border border-indigo-500/30 px-2 py-0.5 rounded font-mono">
              Side-by-Side Trade-off Audit
            </span>
          </div>
          <p className="text-xs text-slate-400 mt-0.5">
            Side-by-side trade-off ledger detailing destination queue reductions vs origin service impacts for every recommended bus movement.
          </p>
        </div>

        {/* Operator ID Entry */}
        <div className="flex items-center space-x-2 bg-slate-950 border border-slate-800 p-2 rounded-xl text-xs font-mono">
          <UserCheck className="w-4 h-4 text-emerald-400" />
          <span className="text-slate-400 text-[10px]">OPERATOR ID:</span>
          <input
            type="text"
            value={operatorId}
            onChange={(e) => setOperatorId(e.target.value)}
            className="bg-slate-900 border border-slate-700 text-white font-bold rounded px-2 py-0.5 w-24 focus:outline-none text-xs"
          />
        </div>
      </div>

      {/* Estimates Notice Banner */}
      <div className="bg-indigo-500/10 border border-indigo-500/20 p-2.5 rounded-xl my-4 text-xs text-indigo-200 flex items-center space-x-2 font-mono">
        <Info className="w-4 h-4 text-indigo-400 shrink-0" />
        <span>
          Projected queue reductions and arrival times are estimates generated by OR-Tools optimization over scenario &apos;{scenarioName}&apos;.
        </span>
      </div>

      {/* Ledger List View (Side-by-Side Design) */}
      {transfers.length === 0 ? (
        <div className="py-12 text-center border border-dashed border-slate-800 rounded-xl my-4 text-xs font-mono text-slate-400">
          No bus transfers recommended in this baseline state. Fleet allocation is currently optimal.
        </div>
      ) : (
        <div className="space-y-4">
          {transfers.map((t) => (
            <div
              key={t.id}
              className="bg-slate-950/90 border border-slate-800 hover:border-indigo-500/50 rounded-2xl p-4 shadow-xl transition-all font-mono"
            >
              {/* Vector Header Row */}
              <div className="flex flex-wrap items-center justify-between gap-3 pb-3 border-b border-slate-800/80">
                <div className="flex items-center space-x-3">
                  <span className="bg-indigo-500/20 text-indigo-300 font-bold px-3 py-1 rounded-xl text-xs flex items-center space-x-1.5 border border-indigo-500/30">
                    <Bus className="w-3.5 h-3.5" />
                    <span>{t.bus_count} BUSES</span>
                  </span>
                  <div className="flex items-center space-x-2 text-sm font-bold text-white">
                    <span>{t.origin_stop_name}</span>
                    <ArrowRight className="w-4 h-4 text-indigo-400" />
                    <span className="text-indigo-300">{t.destination_stop_name}</span>
                  </div>
                </div>

                <div className="flex items-center space-x-3 text-xs text-slate-400">
                  <div className="flex items-center space-x-1">
                    <Clock className="w-3.5 h-3.5 text-purple-400" />
                    <span>
                      Dispatch: <strong className="text-white">{t.dispatch_time_label}</strong> → Arrive:{' '}
                      <strong className="text-white">{t.arrival_time_label}</strong>
                    </span>
                  </div>

                  <span
                    className={`px-2.5 py-1 rounded-lg text-[10px] font-bold uppercase border ${t.approval_status === 'APPROVED'
                      ? 'bg-emerald-500/20 text-emerald-300 border-emerald-500/40'
                      : t.approval_status === 'REJECTED'
                        ? 'bg-rose-500/20 text-rose-300 border-rose-500/40'
                        : 'bg-amber-500/20 text-amber-300 border-amber-500/40'
                      }`}
                  >
                    {t.approval_status}
                  </span>
                </div>
              </div>

              {/* Side-by-Side Trade-Off Analysis */}
              <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mt-3 pt-1">

                {/* 1. Destination Benefit (Left Column) */}
                <div className="bg-emerald-500/10 border border-emerald-500/20 p-3.5 rounded-xl space-y-1">
                  <div className="flex items-center justify-between">
                    <span className="text-[11px] font-bold text-emerald-300 uppercase flex items-center space-x-1">
                      <CheckCircle className="w-3.5 h-3.5 text-emerald-400" />
                      <span>DESTINATION BENEFIT</span>
                    </span>
                    <span className="text-xs font-bold text-emerald-400">
                      {t.expected_destination_queue_change || -t.bus_count * 60} pax
                    </span>
                  </div>
                  <p className="text-xs text-emerald-200/90 leading-relaxed font-sans mt-1">
                    {t.destination_benefit_explanation}
                  </p>
                </div>

                {/* 2. Origin Service Impact (Right Column - Side-by-Side) */}
                <div className="bg-slate-900 border border-slate-800 p-3.5 rounded-xl space-y-1">
                  <div className="flex items-center justify-between">
                    <span className="text-[11px] font-bold text-purple-300 uppercase flex items-center space-x-1">
                      <ShieldAlert className="w-3.5 h-3.5 text-purple-400" />
                      <span>ORIGIN SERVICE IMPACT</span>
                    </span>
                    <span className="text-xs font-bold text-slate-300">
                      Min Service: {t.min_service_status || 'SATISFIED'}
                    </span>
                  </div>
                  <p className="text-xs text-slate-300 leading-relaxed font-sans mt-1">
                    {t.origin_impact_explanation}
                  </p>
                </div>

              </div>

              {/* Card Footer Operator Actions */}
              <div className="flex items-center justify-between pt-3 mt-3 border-t border-slate-800/80 text-xs text-slate-400">
                <div className="flex items-center space-x-3 text-[10px]">
                  <span>Fleet Audit: <strong className="text-emerald-400">{t.fleet_conservation_status || 'VERIFIED'}</strong></span>
                  <span>Run ID: <strong className="text-indigo-300">{t.run_id || 'run-001'}</strong></span>
                </div>

                {t.approval_status === 'RECOMMENDED' ? (
                  <div className="flex items-center space-x-2">
                    <button
                      onClick={() => onApprove(t.id, operatorId)}
                      className="bg-emerald-600 hover:bg-emerald-500 text-white px-3 py-1 rounded-lg text-xs font-bold transition-all flex items-center space-x-1 shadow-md active:scale-95"
                    >
                      <CheckCircle className="w-3.5 h-3.5" />
                      <span>Approve Recommendation</span>
                    </button>

                    <button
                      onClick={() => onReject(t.id, operatorId)}
                      className="bg-slate-800 hover:bg-rose-600 text-slate-300 hover:text-white px-3 py-1 rounded-lg text-xs font-bold transition-all border border-slate-700 active:scale-95"
                    >
                      <XCircle className="w-3.5 h-3.5 inline mr-1" />
                      <span>Reject</span>
                    </button>
                  </div>
                ) : (
                  <span className="text-[11px] text-slate-400 italic">
                    Decision logged by {t.approved_by || operatorId} at {t.approved_at ? new Date(t.approved_at).toLocaleTimeString() : 'now'}
                  </span>
                )}
              </div>

            </div>
          ))}
        </div>
      )}

    </div>
  );
};
